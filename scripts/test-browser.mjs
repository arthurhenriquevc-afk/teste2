import { chromium } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import fs from 'node:fs';
import { deployment } from '../src/config/deployment.mjs';
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox']});
const root=new URL(deployment.base,'http://localhost:4321').href;
const results=[];
const check=(condition,message)=>{if(!condition)throw Error(message);results.push(message);};
try {
 const desktopContext=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
 const page=await desktopContext.newPage();
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const requests=[];page.on('request',r=>requests.push(r.url()));
 await page.goto(root);await page.evaluate(()=>document.fonts.ready);
 await page.locator('[data-mega="Empresas"]').click();
 check(await page.locator('#panel-Empresas .service-card').count()===8,'Mega menu: 8 serviços de empresas');
 await page.locator('#tab-Empresas').press('ArrowRight');
 check(await page.locator('#tab-Profissionais').getAttribute('aria-selected')==='true','Abas: setas alteram seleção e foco');
 check(await page.locator('#panel-Profissionais .service-card').count()===2,'Mega menu: 2 serviços de profissionais');
 await page.keyboard.press('Escape');
 check(await page.locator('#mega-menu').isHidden(),'Esc fecha mega menu');
 check(await page.locator('[data-mega="Empresas"]').evaluate(e=>e===document.activeElement),'Foco devolvido ao acionador');
 await page.locator('[data-hero-next]').click();
 check(await page.locator('[data-slide]:visible').getAttribute('aria-label')==='2 de 3','Carrossel avança');
 await page.locator('[data-hero-next]').click();
 await page.locator('[data-filter-target="Profissionais"]').click();
 await page.waitForTimeout(180);
 check(await page.locator('[data-window]:visible').count()===2,'Filtro profissionais: duas janelas');
 check(await page.locator('[data-window-service]:visible').count()===2,'Filtro profissionais: dois serviços');
 check((await page.locator('[data-window-count]').textContent()).includes('02'),'Contador reflete filtro');
 await page.locator('[data-window-next]').click();await page.waitForTimeout(180);
 check(await page.locator('[data-window-count]').textContent()==='02 / 02','Avançar reflete janela final');
 await page.locator('[data-window-filter="Todos"]').click();
 check(await page.locator('[data-window]:visible').count()===7,'Filtro todos restaura sete janelas');
 await page.locator('.window-track').focus();await page.keyboard.press('ArrowRight');await page.waitForTimeout(200);
 check(await page.locator('[data-window-count]').textContent()==='02 / 07','Janelas: seta do teclado');
 await page.locator('summary').first().click();check(await page.locator('details').first().getAttribute('open')!==null,'FAQ nativo abre');
 await page.locator('button[type=submit]').click();
 check(await page.locator('#stage').getAttribute('aria-invalid')==='true','Formulário identifica obrigatório');
 check(await page.locator('#stage').evaluate(e=>e===document.activeElement),'Formulário foca primeiro erro');
 await page.locator('#stage').selectOption({label:'Antes do fechamento'});
 await page.locator('#name').fill('Teste local');await page.locator('#phone').fill('47999990000');
 check(await page.locator('#phone').inputValue()==='(47) 99999-0000','Máscara de WhatsApp');
 await page.locator('#city').selectOption({label:'Itajaí'});
 await page.locator('#email').fill('invalido');await page.locator('button[type=submit]').click();
 check(await page.locator('#email').getAttribute('aria-invalid')==='true','E-mail opcional validado se preenchido');
 await page.locator('#email').fill('');
 await page.evaluate(()=>{window.open=(url)=>{window.__submittedURL=String(url);return null;};});
 await page.locator('button[type=submit]').click();
 const submitted=await page.evaluate(()=>window.__submittedURL);
 check(submitted?.startsWith('https://wa.me/5547996490312?text='),'Envio usa WhatsApp correto');
 const message=new URL(submitted).searchParams.get('text');
 check(message==='Em que etapa a obra está: Antes do fechamento\nNome: Teste local\nWhatsApp: (47) 99999-0000\nCidade da obra: Itajaí','Mensagem contém só rótulos e valores preenchidos');
 const axe=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze();
 fs.writeFileSync('reports/axe-desktop.json',JSON.stringify(axe,null,2));
 check(axe.violations.length===0,'axe desktop: nenhuma violação AA');
 await page.reload();await page.evaluate(()=>document.fonts.ready);await page.evaluate(()=>window.scrollTo(0,0));await page.waitForTimeout(120);
 for(const width of [320,390,768,1280,1600]){await page.setViewportSize({width,height:900});await page.waitForTimeout(100);check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`Sem overflow horizontal em ${width}px`);}
 await page.setViewportSize({width:720,height:500});
 check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Reflow equivalente a 200% em tela de 1440px');
 const mobileContext=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,reducedMotion:'reduce'});
 const mobile=await mobileContext.newPage();
 await mobile.goto(root);await mobile.evaluate(()=>document.fonts.ready);
 await mobile.locator('.mobile-toggle').click();check(await mobile.locator('#main-nav').isVisible(),'Menu mobile abre');
 await mobile.locator('[data-mega="Profissionais"]').click();check(await mobile.locator('#panel-Profissionais').isVisible(),'Serviços acessíveis no menu mobile');
 const mobileAxe=await new AxeBuilder({page:mobile}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze();
 fs.writeFileSync('reports/axe-mobile.json',JSON.stringify(mobileAxe,null,2));check(mobileAxe.violations.length===0,'axe mobile com menu aberto: nenhuma violação AA');
 await mobile.keyboard.press('Escape');await mobile.locator('.mobile-toggle').click();
 await mobile.evaluate(()=>window.scrollTo(0,0));await mobile.waitForTimeout(120);
 const nojs=await browser.newPage({javaScriptEnabled:false,viewport:{width:390,height:844}});
 await nojs.goto(root);
 check(await nojs.locator('[data-slide]:visible').count()===3,'Sem JS: três slides acessíveis');
 check(await nojs.locator('[data-window]:visible').count()===7,'Sem JS: sete janelas acessíveis');
 check(await nojs.locator('a', {hasText:'Falar pelo WhatsApp agora'}).getAttribute('href')==='https://wa.me/5547996490312','Sem JS: contato direto disponível');
 await nojs.locator('summary').first().click();check(await nojs.locator('details').first().getAttribute('open')!==null,'Sem JS: FAQ funciona');
 check(errors.length===0,'Sem erros JavaScript');
 check(requests.every(url=>url.startsWith('http://localhost:4321/')),'Sem solicitações a terceiros no carregamento');
 await page.setViewportSize({width:1440,height:1000});await page.evaluate(()=>window.scrollTo(0,0));await page.waitForTimeout(100);await page.screenshot({path:'.impeccable/review/desktop.png',fullPage:true});
 await mobile.evaluate(()=>window.scrollTo(0,0));await mobile.waitForTimeout(100);await mobile.screenshot({path:'.impeccable/review/mobile.png',fullPage:true});
 console.log(results.join('\n'));
 fs.writeFileSync('reports/browser.json',JSON.stringify({passed:results.length,checks:results,errors},null,2));
} finally {await browser.close();}
